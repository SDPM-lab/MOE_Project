const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function tocXml() {
  const rpr = (lvl) => `<w:rPr><w:rFonts w:ascii="${FONT.ascii}" w:hAnsi="${FONT.hAnsi}" w:eastAsia="${FONT.eastAsia}" w:cs="${FONT.cs}"/>${lvl === 1 ? '<w:b/><w:bCs/>' : ''}<w:sz w:val="${lvl === 1 ? 24 : 22}"/><w:szCs w:val="${lvl === 1 ? 24 : 22}"/></w:rPr>`;
  return toc.map((e, i) => {
    const ppr = `<w:pPr><w:tabs><w:tab w:val="right" w:leader="dot" w:pos="9638"/></w:tabs><w:spacing w:before="${e.level === 1 ? 120 : 20}" w:after="0" w:line="${e.level === 1 ? 360 : 320}" w:lineRule="exact"/><w:ind w:left="${e.level === 1 ? 0 : 360}" w:right="400"/></w:pPr>`;
    const begin = i === 0 ? '<w:r><w:fldChar w:fldCharType="begin"/></w:r><w:r><w:instrText xml:space="preserve"> TOC \\o "1-2" \\h \\z \\u </w:instrText></w:r><w:r><w:fldChar w:fldCharType="separate"/></w:r>' : '';
    const end = i === toc.length - 1 ? '<w:r><w:fldChar w:fldCharType="end"/></w:r>' : '';
    const page = String(tocPages[e.text] ?? 0);
    return `<w:p>${ppr}${begin}<w:r>${rpr(e.level)}<w:t xml:space="preserve">${esc(e.text)}</w:t></w:r><w:r>${rpr(e.level)}<w:tab/></w:r><w:r>${rpr(e.level)}<w:t>${page}</w:t></w:r>${end}</w:p>`;
  }).join('');
}
function injectToc(xml) {
  const at = xml.indexOf('@@TOC@@');
  if (at < 0) throw new Error('TOC marker not found');
  const s = Math.max(xml.lastIndexOf('<w:p>', at), xml.lastIndexOf('<w:p ', at));
  const e = xml.indexOf('</w:p>', at) + '</w:p>'.length;
  return xml.slice(0, s) + tocXml() + xml.slice(e);
}

